/// <summary>
/// Serializes nested function/custom tools inside a namespace.
/// </summary>
internal class ResponseNamespaceNestedToolListConverter : JsonConverter<List<ResponseTool>>
{
    public override List<ResponseTool>? ReadJson(JsonReader reader, Type objectType, List<ResponseTool>? existingValue, bool hasExistingValue, JsonSerializer serializer)
    {
        if (reader.TokenType == JsonToken.Null)
        {
            return null;
        }

        JArray array = JArray.Load(reader);
        List<ResponseTool> result = [];

        foreach (JToken? token in array)
        {
            if (token is not JObject jo)
            {
                continue;
            }

            ResponseTool? tool = jo["type"]?.ToString() switch
            {
                "function" => new ResponseFunctionTool
                {
                    Name = (string)jo["name"]!,
                    Description = (string?)jo["description"],
                    Parameters = jo["parameters"] as JObject,
                    Strict = (bool?)jo["strict"],
                    DeferLoading = (bool?)jo["defer_loading"]
                },
                "custom" => ResponseCustomTool.FromJson(jo),
                _ => null
            };

            if (tool is not null)
            {
                result.Add(tool);
            }
        }

        return result;
    }

    public override void WriteJson(JsonWriter writer, List<ResponseTool>? value, JsonSerializer serializer)
    {
        if (value is null)
        {
            writer.WriteNull();
            return;
        }

        writer.WriteStartArray();
        foreach (ResponseTool tool in value)
        {
            switch (tool)
            {
                case ResponseFunctionTool func:
                    writer.WriteStartObject();
                    writer.WritePropertyName("type");
                    writer.WriteValue(func.Type);
                    writer.WritePropertyName("name");
                    writer.WriteValue(func.Name);
                    if (func.Description is not null)
                    {
                        writer.WritePropertyName("description");
                        writer.WriteValue(func.Description);
                    }
                    if (func.DeferLoading is not null)
                    {
                        writer.WritePropertyName("defer_loading");
                        writer.WriteValue(func.DeferLoading);
                    }
                    if (func.Parameters is not null)
                    {
                        writer.WritePropertyName("parameters");
                        serializer.Serialize(writer, func.Parameters);
                    }
                    if (func.Strict is not null)
                    {
                        writer.WritePropertyName("strict");
                        writer.WriteValue(func.Strict);
                    }
                    writer.WriteEndObject();
                    break;
                case ResponseCustomTool custom:
                    serializer.Serialize(writer, custom);
                    break;
            }
        }
        writer.WriteEndArray();
    }
}
