/// <summary>
/// Whether tool search is executed by the server or by the client.
/// </summary>
[JsonConverter(typeof(StringEnumConverter))]
public enum ResponseToolSearchExecution
{
    /// <summary>
    /// OpenAI searches deferred tools declared in the request.
    /// </summary>
    [EnumMember(Value = "server")]
    Server,

    /// <summary>
    /// The model emits a tool search call and the client performs the lookup.
    /// </summary>
    [EnumMember(Value = "client")]
    Client
}

/// <summary>
/// Hosted or client-executed tool search configuration for deferred tools.
/// </summary>
public class ResponseToolSearchTool : ResponseTool
{
    /// <inheritdoc />
    public override string Type => "tool_search";

    /// <summary>
    /// Whether tool search is executed by the server or by the client.
    /// </summary>
    [JsonProperty("execution")]
    public ResponseToolSearchExecution? Execution { get; set; }

    /// <summary>
    /// Description shown to the model for a client-executed tool search tool.
    /// </summary>
    [JsonProperty("description")]
    public string? Description { get; set; }

    /// <summary>
    /// Parameter schema for a client-executed tool search tool.
    /// </summary>
    [JsonProperty("parameters")]
    public JObject? Parameters { get; set; }
}

/// <summary>
/// Groups function or custom tools under a shared namespace for tool search.
/// </summary>
public class ResponseToolNamespace : ResponseTool
{
    /// <inheritdoc />
    public override string Type => "namespace";

    /// <summary>
    /// The namespace name used in tool calls (for example, <c>crm</c>).
    /// </summary>
    [JsonProperty("name", Required = Required.Always)]
    public string Name { get; set; } = null!;

    /// <summary>
    /// A description of the namespace shown to the model.
    /// </summary>
    [JsonProperty("description", Required = Required.Always)]
    public string Description { get; set; } = null!;

    /// <summary>
    /// The function or custom tools available inside this namespace.
    /// </summary>
    [JsonProperty("tools", Required = Required.Always)]
    [JsonConverter(typeof(ResponseNamespaceNestedToolListConverter))]
    public List<ResponseTool> Tools { get; set; } = [];
}

